//Realiza un programa que muestre los números pares comprendidos entre el 1 y el 200. Para ello utiliza un contador y suma de 2 en 2.
public class EJER4 {
    public static void main (){
        int num= 2;
        while (num<=200) {
            System.out.println("LOS NUMEROS SON: "+num);
            num=num+2;
        }
    }
}